
import sys
from pathlib import Path
sys.path.append(str(Path(__file__).parent/"src"))
import streamlit as st
import pandas as pd
import numpy as np
import plotly.express as px
from metrics import add_engagement_metrics
from sentiment import label_comment

st.set_page_config(page_title="Social Engagement Intelligence",page_icon="📊",layout="wide")
st.title("📊 Social Engagement Intelligence")
st.caption("Measure connection • Understand audience sentiment • Optimize content strategy")
DATA=Path(__file__).parent/"data"
posts=pd.read_csv(DATA/"social_posts.csv",parse_dates=["date"])
comments=pd.read_csv(DATA/"comments.csv")
trends=pd.read_csv(DATA/"hashtag_trends.csv",parse_dates=["date"])
posts,threshold=add_engagement_metrics(posts)
comments[["predicted_sentiment","relatability"]] = comments["comment_text"].apply(lambda x: pd.Series(label_comment(x)))

with st.sidebar:
    st.header("Dashboard filters")
    topic=st.multiselect("Topics",sorted(posts.topic.unique()),default=sorted(posts.topic.unique()))
    fmt=st.multiselect("Content formats",sorted(posts.content_format.unique()),default=sorted(posts.content_format.unique()))
    date_min,date_max=posts.date.min().date(),posts.date.max().date()
    date_range=st.date_input("Date range",value=(date_min,date_max),min_value=date_min,max_value=date_max)
    st.caption("Demo dataset: synthetic records, not real platform analytics.")

if len(date_range)==2:
    start,end=date_range
    f=posts[(posts.date.dt.date>=start)&(posts.date.dt.date<=end)&posts.topic.isin(topic)&posts.content_format.isin(fmt)]
else: f=posts[posts.topic.isin(topic)&posts.content_format.isin(fmt)]
if f.empty:
    st.warning("No records match the selected filters.")
    st.stop()

c1,c2,c3,c4,c5=st.columns(5)
c1.metric("Posts",f"{len(f):,}")
c2.metric("Avg. engagement rate",f"{f.engagement_rate.mean():.2f}%")
c3.metric("Total shares",f"{f.shares.sum():,}")
c4.metric("Total saves",f"{f.saves.sum():,}")
c5.metric("Avg. retention",f"{f.retention_rate.mean():.1f}%")

tab1,tab2,tab3,tab4,tab5=st.tabs(["Overview","Virality","Audience voice","Experiment analysis","Recommendations & trends"])
with tab1:
    left,right=st.columns(2)
    daily=f.groupby("date",as_index=False).agg(engagement_rate=("engagement_rate","mean"),reach=("reach","sum"))
    left.plotly_chart(px.line(daily,x="date",y="engagement_rate",title="Daily average engagement rate"),use_container_width=True)
    right.plotly_chart(px.bar(f.groupby("topic",as_index=False).engagement_rate.mean().sort_values("engagement_rate",ascending=False),x="topic",y="engagement_rate",title="Engagement rate by topic"),use_container_width=True)
    st.plotly_chart(px.box(f,x="content_format",y="engagement_rate",color="content_format",title="Engagement distribution by content format"),use_container_width=True)
with tab2:
    st.subheader("Virality prediction proxy")
    st.info("Viral coefficient is a weighted engagement proxy, not proof that a post will go viral.")
    st.metric("80th percentile threshold",f"{threshold:.4f}")
    st.plotly_chart(px.scatter(f,x="share_rate",y="save_rate",size="reach",color="topic",hover_data=["post_id","viral_coefficient"],title="Share rate vs save rate"),use_container_width=True)
    st.dataframe(f.nlargest(10,"viral_coefficient")[["post_id","topic","content_format","viral_coefficient","engagement_rate","followers_gained"]],use_container_width=True)
with tab3:
    c=comments[comments.post_id.isin(f.post_id)]
    counts=c.predicted_sentiment.value_counts().rename_axis("sentiment").reset_index(name="comments")
    l,r=st.columns(2)
    l.plotly_chart(px.pie(counts,names="sentiment",values="comments",title="Comment sentiment (lexicon baseline)"),use_container_width=True)
    r.plotly_chart(px.bar(c.relatability.value_counts().rename_axis("label").reset_index(name="comments"),x="label",y="comments",title="Relatability signals"),use_container_width=True)
    st.caption("The sentiment/relatability labels are generated by a simple word-list baseline and require human validation.")
    st.dataframe(c[["comment_text","predicted_sentiment","relatability"]].head(20),use_container_width=True)
with tab4:
    st.subheader("Exploratory A/B-style comparisons")
    group=st.selectbox("Compare variants by",["content_format","hook_type","caption_length"])
    metric=st.selectbox("Outcome metric",["engagement_rate","share_rate","save_rate","retention_rate"])
    summary=f.groupby(group)[metric].agg(["count","mean","median"]).reset_index()
    st.dataframe(summary,use_container_width=True)
    st.caption("Pairwise Mann–Whitney tests are exploratory. These observational synthetic groups are not randomized experiments and do not establish causality.")
    from scipy.stats import mannwhitneyu
    vals=[(x,g[metric].dropna().values) for x,g in f.groupby(group)]
    pairs=[]
    for i in range(len(vals)):
        for j in range(i+1,len(vals)):
            if len(vals[i][1]) and len(vals[j][1]):
                _,p=mannwhitneyu(vals[i][1],vals[j][1],alternative="two-sided")
                pairs.append({"variant_a":vals[i][0],"variant_b":vals[j][0],"p_value":p})
    st.dataframe(pd.DataFrame(pairs),use_container_width=True)
with tab5:
    st.subheader("Content strategy suggestions")
    rec=f.groupby(["topic","content_format","hook_type"]).agg(posts=("post_id","count"),engagement=("engagement_rate","mean"),save_rate=("save_rate","mean"),share_rate=("share_rate","mean")).reset_index()
    rec=rec[rec.posts>=5].sort_values(["engagement","save_rate"],ascending=False)
    st.dataframe(rec.head(15),use_container_width=True)
    st.subheader("Hashtag trend signals")
    tf=trends.groupby(["date","hashtag"],as_index=False).trend_score.mean()
    st.plotly_chart(px.line(tf,x="date",y="trend_score",color="hashtag",title="Synthetic hashtag trend scores"),use_container_width=True)
    st.caption("Trend scores are simulated. Replace with platform-approved API data for real trend monitoring.")

st.divider()
st.caption("Research prototype. Not affiliated with Instagram, YouTube, or any social platform.")
